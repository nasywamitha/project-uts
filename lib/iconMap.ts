// Helper component untuk menampilkan ikon di tabel maupun modal
export function CategoryIcon({
  name,
  className = 'w-5 h-5',
}: {
  name: string;
  className?: string;
}) {
  const IconComponent = iconMap[name] || Wallet;
  return React.createElement(IconComponent, { className });
}